-- =============================================================================
-- M03 (EC-102, D86): full export. One zip of every table of the shop as CSV and JSON, built by a
-- background job in ONE read-only snapshot, with a manifest of row counts and control totals.
--
--   public.start_full_export(body, key)   export.data (works in an expired shop; a suspended one can't)
--   public.list_exports / get_export      export.data
--   public.record_export_download(file)   export.data; audits the download of a zip (F14 does not audit reads)
--   public.cancel_export(id)              export.data
--   public.jobs_export_*                  service role: prepare, state, counts, totals, page, complete,
--                                         fail, cleanup_list, cleanup_done
--
-- An export is ONE import_jobs row (kind full_export) WITHOUT the 'columns' key in its report, so
-- M01's reads and runs (which all filter `report ? 'columns'`) never see it. status importing is
-- 'queued' until jobs_export_prepare sets report.started_at, then 'running'.
--
-- Which tables: every public base table with organization_id, minus app.export_excluded_tables()
-- (each with its reason), plus 'organizations'. Which columns: all, minus app.export_excluded_
-- columns(). National IDs are masked (app.mask_national_id) unless the export is pii = full, which
-- needs customer.view_pii on top of export.data and is audited at warning. SQL tests fail when a
-- tenant table is neither exported nor excluded with a reason, or a secret-looking column leaks.
--
-- Changes beyond the spec (D86): files.deleted_at (the zip is removed after 7 days and the files row
-- stays: rows of public.files are never deleted); the tenant-files bucket limit goes from 10 MB to
-- 500 MB; the page function takes the previous page's key values as text[] (works for composite
-- primary keys too) and returns text rows, not jsonb[], so numbers keep their exact text.
-- =============================================================================

ALTER TABLE public.files ADD COLUMN deleted_at timestamptz;

DO $$
BEGIN
    IF to_regclass('storage.buckets') IS NOT NULL THEN
        UPDATE storage.buckets SET file_size_limit = 524288000 WHERE id = 'tenant-files';
    END IF;
END $$;

-- 1. What is exported ----------------------------------------------------------------------------

-- Tenant tables that are deliberately NOT exported, each with its reason.
CREATE FUNCTION app.export_excluded_tables()
RETURNS TABLE (table_name text, reason text)
LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$
    VALUES
    ('jobs', 'the background queue: transient work items, rebuilt by the system'),
    ('password_resets', 'one-time reset tokens (secrets)'),
    ('day_checks', 'the nightly check output (K04): derived data, regenerated by the day.check job'),
    ('document_counters', 'gap-free number counters: the next number is derived from the documents'' own numbers')
$$;

-- Columns that never leave the database. table_name '*' = every table; column_pattern is a LIKE.
CREATE FUNCTION app.export_excluded_columns()
RETURNS TABLE (table_name text, column_pattern text, reason text)
LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$
    VALUES
    ('*', 'token\_hash', 'hash of a login or invitation token'),
    ('*', '%\_secret%', 'secret material or a pointer to it (vault ids)'),
    ('*', 'password%', 'password material'),
    ('*', 'pairing\_code%', 'device pairing code (hash)'),
    ('devices', 'eta\_preshared\_key\_vault\_id', 'ETA signing material (vault id)')
$$;

CREATE FUNCTION app.export_column_excluded(p_table text, p_column text)
RETURNS boolean
LANGUAGE sql STABLE SET search_path = ''
AS $$
    SELECT EXISTS (SELECT 1 FROM app.export_excluded_columns() x
                   WHERE (x.table_name = '*' OR x.table_name = p_table) AND p_column LIKE x.column_pattern)
$$;

-- The exported tables, alphabetical.
CREATE FUNCTION app.export_tables()
RETURNS text[]
LANGUAGE sql STABLE SET search_path = ''
AS $$
    SELECT array_agg(t.name ORDER BY t.name) FROM (
        SELECT c.relname::text AS name
        FROM pg_catalog.pg_class c
        WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p')
          AND EXISTS (SELECT 1 FROM pg_catalog.pg_attribute a
                      WHERE a.attrelid = c.oid AND a.attname = 'organization_id' AND NOT a.attisdropped)
          AND c.relname::text NOT IN (SELECT x.table_name FROM app.export_excluded_tables() x)
        UNION
        SELECT 'organizations'
    ) t
$$;

-- Primary key columns in key order (the order of the keyset paging).
CREATE FUNCTION app.export_key_columns(p_table text)
RETURNS text[]
LANGUAGE sql STABLE SET search_path = ''
AS $$
    SELECT array_agg(a.attname::text ORDER BY k.ord)
    FROM pg_catalog.pg_index i
    CROSS JOIN LATERAL unnest(i.indkey::smallint[]) WITH ORDINALITY k(attnum, ord)
    JOIN pg_catalog.pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum
    WHERE i.indrelid = ('public.' || quote_ident(p_table))::regclass AND i.indisprimary
$$;

-- The exported columns of one table in table order. Refuses a table that is not in the export.
CREATE FUNCTION app.export_columns(p_table text)
RETURNS text[]
LANGUAGE plpgsql STABLE SET search_path = ''
AS $$
DECLARE v_cols text[];
BEGIN
    IF p_table IS NULL OR NOT (p_table = ANY (app.export_tables())) THEN
        RAISE EXCEPTION 'EXPORT_TABLE_NOT_ALLOWED: %', p_table USING ERRCODE = 'P0001';
    END IF;
    SELECT array_agg(a.attname::text ORDER BY a.attnum) INTO v_cols
    FROM pg_catalog.pg_attribute a
    WHERE a.attrelid = ('public.' || quote_ident(p_table))::regclass AND a.attnum > 0 AND NOT a.attisdropped
      AND NOT app.export_column_excluded(p_table, a.attname::text);
    RETURN v_cols;
END;
$$;

-- The WHERE of a tenant table for one shop ($1 = the shop id).
CREATE FUNCTION app.export_org_filter(p_table text)
RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$ SELECT CASE WHEN p_table = 'organizations' THEN 't.id = $1' ELSE 't.organization_id = $1' END $$;

-- National IDs masked exactly as R01 does; anything that is not an object is returned as it is.
CREATE FUNCTION app.export_mask_json(p_json jsonb)
RETURNS jsonb
LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$
    SELECT CASE
        WHEN jsonb_typeof(p_json) = 'object' AND jsonb_typeof(p_json -> 'national_id') = 'string'
        THEN jsonb_set(p_json, '{national_id}', to_jsonb(app.mask_national_id(p_json ->> 'national_id')))
        ELSE p_json
    END
$$;

-- 2. The control totals (same snapshot as the rows when the caller holds one) --------------------

CREATE FUNCTION app.export_totals(p_org uuid)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT jsonb_build_object(
        'cash_balance_total', (SELECT COALESCE(sum(b.balance), 0)::numeric(18,2)::text
                               FROM public.cash_balances b WHERE b.organization_id = p_org),
        'stock_on_hand_total', (SELECT COALESCE(sum(s.on_hand), 0)::bigint::text
                                FROM public.stock_levels s WHERE s.organization_id = p_org),
        'store_credit_total', (SELECT COALESCE(sum(b.balance), 0)::numeric(18,2)::text
                               FROM public.store_credit_balances b WHERE b.organization_id = p_org),
        'open_contracts_remaining', (SELECT COALESCE(sum(v.remaining), 0)::numeric(18,2)::text
                                     FROM public.v_contract_balances v
                                     WHERE v.organization_id = p_org AND v.status IN ('active', 'rescheduled')),
        'sales_total', (SELECT COALESCE(sum(s.total), 0)::numeric(18,2)::text
                        FROM public.sales s WHERE s.organization_id = p_org),
        'payments_in_total', (SELECT COALESCE(sum(p.amount), 0)::numeric(18,2)::text
                              FROM public.payments p WHERE p.organization_id = p_org AND p.direction = 'in'),
        'payments_out_total', (SELECT COALESCE(sum(p.amount), 0)::numeric(18,2)::text
                               FROM public.payments p WHERE p.organization_id = p_org AND p.direction = 'out'),
        'audit_rows', (SELECT count(*) FROM public.audit_log a WHERE a.organization_id = p_org))
$$;

-- Exact row count of every exported table for one shop: { table: n }.
CREATE FUNCTION app.export_counts(p_org uuid)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_t text; v_n bigint; v_out jsonb := '{}'::jsonb;
BEGIN
    FOREACH v_t IN ARRAY app.export_tables() LOOP
        EXECUTE format('SELECT count(*) FROM public.%I t WHERE %s', v_t, app.export_org_filter(v_t)) INTO v_n USING p_org;
        v_out := v_out || jsonb_build_object(v_t, v_n);
    END LOOP;
    RETURN v_out;
END;
$$;

-- 3. An export as the API returns it -------------------------------------------------------------

CREATE FUNCTION app.export_job_json(j public.import_jobs)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT jsonb_build_object(
        'id', j.id,
        'status', CASE j.status
                      WHEN 'importing' THEN CASE WHEN j.report ? 'started_at' THEN 'running' ELSE 'queued' END
                      ELSE j.status::text END,
        'requested_by', (SELECT jsonb_build_object('id', e.id, 'name', e.full_name) FROM public.employees e
                         WHERE e.id = j.created_by AND e.organization_id = j.organization_id),
        'requested_at', j.created_at,
        'finished_at', j.finished_at,
        'pii', COALESCE(j.report ->> 'pii', 'masked'),
        'rows', j.rows_total,
        'size_bytes', NULLIF(j.report ->> 'size_bytes', '')::bigint,
        -- The zip of a full-PII export is not offered to a caller without customer.view_pii.
        'file_id', (SELECT f.id FROM public.files f
                    WHERE f.id = j.result_file_id AND f.organization_id = j.organization_id AND f.deleted_at IS NULL
                      AND (COALESCE(j.report ->> 'pii', 'masked') <> 'full' OR app.has_permission('customer.view_pii'))),
        'file_name', (SELECT f.original_name FROM public.files f
                      WHERE f.id = j.result_file_id AND f.organization_id = j.organization_id AND f.deleted_at IS NULL
                        AND (COALESCE(j.report ->> 'pii', 'masked') <> 'full' OR app.has_permission('customer.view_pii'))),
        'file_removed_at', (SELECT f.deleted_at FROM public.files f
                            WHERE f.id = j.result_file_id AND f.organization_id = j.organization_id),
        'error_code', j.report ->> 'error_code')
$$;

-- 4. Start, list, read, cancel (export.data) -----------------------------------------------------

CREATE FUNCTION public.start_full_export(p_body jsonb, p_idempotency_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    v_emp uuid; v_org uuid; v_pii text := 'masked'; v_job public.import_jobs; v_last timestamptz; v_key text;
BEGIN
    v_emp := app.require_permission('export.data');
    v_org := app.current_org_id();
    IF p_body IS NULL OR jsonb_typeof(p_body) <> 'object' THEN RAISE EXCEPTION 'VALIDATION_FAILED: body' USING ERRCODE = 'P0001'; END IF;
    SELECT k INTO v_key FROM jsonb_object_keys(p_body) k WHERE k <> 'pii' LIMIT 1;
    IF v_key IS NOT NULL THEN RAISE EXCEPTION 'VALIDATION_FAILED: %', v_key USING ERRCODE = 'P0001'; END IF;
    IF p_body ? 'pii' THEN
        IF jsonb_typeof(p_body -> 'pii') <> 'string' OR (p_body ->> 'pii') NOT IN ('masked', 'full') THEN
            RAISE EXCEPTION 'VALIDATION_FAILED: pii' USING ERRCODE = 'P0001';
        END IF;
        v_pii := p_body ->> 'pii';
    END IF;
    IF v_pii = 'full' AND NOT app.has_permission('customer.view_pii') THEN
        RAISE EXCEPTION 'PERMISSION_DENIED: customer.view_pii' USING ERRCODE = '42501';
    END IF;
    IF p_idempotency_key IS NULL OR length(p_idempotency_key) < 8 OR length(p_idempotency_key) > 128 THEN
        RAISE EXCEPTION 'VALIDATION_FAILED: idempotency_key' USING ERRCODE = 'P0001';
    END IF;

    PERFORM app.lock_idempotency_key(v_org, p_idempotency_key);
    SELECT * INTO v_job FROM public.import_jobs j
    WHERE j.organization_id = v_org AND j.kind = 'full_export' AND j.report ->> 'idempotency_key' = p_idempotency_key;
    IF FOUND THEN
        RETURN app.export_job_json(v_job);                  -- a repeat changes nothing
    END IF;

    SELECT j.* INTO v_job FROM public.import_jobs j
    WHERE j.organization_id = v_org AND j.kind = 'full_export' AND j.status = 'importing'
    ORDER BY j.created_at DESC, j.id DESC LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'EXPORT_RUNNING' USING ERRCODE = 'P0001',
            DETAIL = jsonb_build_object('job_id', v_job.id)::text;
    END IF;
    SELECT max(j.finished_at) INTO v_last FROM public.import_jobs j
    WHERE j.organization_id = v_org AND j.kind = 'full_export' AND j.status = 'completed';
    IF v_last IS NOT NULL AND v_last > now() - interval '1 hour' THEN
        RAISE EXCEPTION 'EXPORT_TOO_SOON' USING ERRCODE = 'P0001',
            DETAIL = jsonb_build_object('retry_after',
                GREATEST(1, ceil(extract(epoch FROM (v_last + interval '1 hour' - now())))::integer))::text;
    END IF;

    INSERT INTO public.import_jobs (organization_id, kind, status, dry_run, report, created_by)
    VALUES (v_org, 'full_export', 'importing', false,
            jsonb_build_object('idempotency_key', p_idempotency_key, 'pii', v_pii, 'requested_by', v_emp,
                               'options', jsonb_build_object('pii', v_pii)),
            v_emp)
    RETURNING * INTO v_job;
    INSERT INTO public.jobs (organization_id, job_type, payload, dedupe_key, max_attempts)
    VALUES (v_org, 'export.full', jsonb_build_object('export_job_id', v_job.id), v_job.id::text, 2);
    PERFORM app.write_audit('export.requested', 'export_job', v_job.id, NULL,
        jsonb_build_object('pii', v_pii), NULL, NULL,
        CASE WHEN v_pii = 'full' THEN 'warning' ELSE 'info' END::public.audit_severity);
    RETURN app.export_job_json(v_job);
END;
$$;

CREATE FUNCTION public.list_exports()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_org uuid;
BEGIN
    PERFORM app.require_permission('export.data');
    v_org := app.current_org_id();
    RETURN jsonb_build_object('items', COALESCE((
        SELECT jsonb_agg(app.export_job_json(s) ORDER BY s.created_at DESC, s.id DESC)
        FROM public.import_jobs s
        WHERE s.id IN (SELECT j.id FROM public.import_jobs j
                       WHERE j.organization_id = v_org AND j.kind = 'full_export'
                       ORDER BY j.created_at DESC, j.id DESC LIMIT 50)), '[]'::jsonb));
END;
$$;

CREATE FUNCTION public.get_export(p_id uuid)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_job public.import_jobs;
BEGIN
    PERFORM app.require_permission('export.data');
    SELECT * INTO v_job FROM public.import_jobs j
    WHERE j.id = p_id AND j.organization_id = app.current_org_id() AND j.kind = 'full_export';
    IF NOT FOUND THEN RAISE EXCEPTION 'EXPORT_NOT_FOUND' USING ERRCODE = 'P0001'; END IF;
