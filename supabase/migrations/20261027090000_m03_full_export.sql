-- The next page of one table, ordered by its primary key (keyset: p_after = the previous page's
-- last key values as text, NULL for the first page). Only the exported columns; national IDs masked
-- unless the export is pii = full. Per row: the JSON text exactly as the database gives it, the
-- cells as text for the CSV (NULL stays NULL) in the table's column order, and the key values.
CREATE FUNCTION public.jobs_export_page(p_job_id uuid, p_table text, p_after text[], p_limit integer)
RETURNS TABLE (row_json text, cells text[], key_vals text[])
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    v_job public.import_jobs; v_cols text[]; v_keys text[]; v_drop text[]; v_expr text := 'to_jsonb(t)';
    v_where text; v_order text; v_kv text; v_masked boolean; v_k text; v_i integer := 0; v_casts text[] := '{}';
BEGIN
    SELECT * INTO v_job FROM public.import_jobs j WHERE j.id = p_job_id AND j.kind = 'full_export';
    IF NOT FOUND THEN RAISE EXCEPTION 'EXPORT_NOT_FOUND' USING ERRCODE = 'P0001'; END IF;
    IF p_limit IS NULL OR p_limit < 1 OR p_limit > 5000 THEN RAISE EXCEPTION 'VALIDATION_FAILED: limit' USING ERRCODE = 'P0001'; END IF;
    v_cols := app.export_columns(p_table);                     -- refuses a table that is not exported
    v_keys := app.export_key_columns(p_table);
    IF v_keys IS NULL THEN RAISE EXCEPTION 'EXPORT_TABLE_NOT_ALLOWED: % has no primary key', p_table USING ERRCODE = 'P0001'; END IF;
    v_masked := COALESCE(v_job.report ->> 'pii', 'masked') <> 'full';

    SELECT COALESCE(array_agg(a.attname::text), '{}') INTO v_drop
    FROM pg_catalog.pg_attribute a
    WHERE a.attrelid = ('public.' || quote_ident(p_table))::regclass AND a.attnum > 0 AND NOT a.attisdropped
      AND NOT (a.attname::text = ANY (v_cols));
    v_expr := format('(%s - %L::text[])', v_expr, v_drop);
    IF v_masked THEN
        IF 'national_id' = ANY (v_cols) THEN
            v_expr := format('app.export_mask_json(%s)', v_expr);
        END IF;
        IF p_table = 'audit_log' THEN
            v_expr := format('jsonb_set(jsonb_set(%1$s, ''{before}'', app.export_mask_json(%1$s -> ''before'')), ''{after}'', app.export_mask_json(%1$s -> ''after''))', v_expr);
        END IF;
    END IF;

    SELECT string_agg(format('t.%I', k), ', ' ORDER BY o) INTO v_order FROM unnest(v_keys) WITH ORDINALITY u(k, o);
    SELECT string_agg(format('t.%I::text', k), ', ' ORDER BY o) INTO v_kv FROM unnest(v_keys) WITH ORDINALITY u(k, o);
    v_where := app.export_org_filter(p_table);
    IF p_after IS NOT NULL THEN
        IF cardinality(p_after) <> cardinality(v_keys) THEN RAISE EXCEPTION 'VALIDATION_FAILED: after' USING ERRCODE = 'P0001'; END IF;
        FOREACH v_k IN ARRAY v_keys LOOP
            v_i := v_i + 1;
            v_casts := v_casts || format('$2[%s]::%s', v_i,
                (SELECT format_type(a.atttypid, a.atttypmod) FROM pg_catalog.pg_attribute a
                 WHERE a.attrelid = ('public.' || quote_ident(p_table))::regclass AND a.attname = v_k));
        END LOOP;
        v_where := v_where || format(' AND (%s) > (%s)',
            (SELECT string_agg(format('t.%I', k), ', ' ORDER BY o) FROM unnest(v_keys) WITH ORDINALITY u(k, o)),
            array_to_string(v_casts, ', '));
    ELSE
        v_where := v_where || ' AND $2 IS NULL';
    END IF;

    RETURN QUERY EXECUTE format(
        'SELECT x.j::text, ARRAY(SELECT x.j ->> u.c FROM unnest($3::text[]) WITH ORDINALITY u(c, o) ORDER BY u.o), x.kv '
        'FROM (SELECT %s AS j, ARRAY[%s] AS kv FROM public.%I t WHERE %s ORDER BY %s LIMIT %s) x',
        v_expr, v_kv, p_table, v_where, v_order, p_limit)
    USING v_job.organization_id, p_after, v_cols;
END;
$$;

-- The zip is stored: records the file, ends the job 'completed' with the manifest in its report.
-- A job that is not 'importing' any more (cancelled while the zip was built) changes nothing and the
-- worker removes the object.
CREATE FUNCTION public.jobs_export_complete(p_job_id uuid, p_file_id uuid, p_path text, p_original_name text,
                                            p_size_bytes bigint, p_sha256 text, p_rows bigint, p_manifest jsonb,
                                            p_uncompressed_bytes bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_job public.import_jobs;
BEGIN
    SELECT * INTO v_job FROM public.import_jobs j WHERE j.id = p_job_id AND j.kind = 'full_export' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'EXPORT_NOT_FOUND' USING ERRCODE = 'P0001'; END IF;
    IF v_job.status <> 'importing' THEN
        RETURN jsonb_build_object('status', v_job.status, 'changed', false);
    END IF;
    IF p_file_id IS NULL OR p_path IS NULL OR p_size_bytes IS NULL OR p_size_bytes < 0
       OR left(p_path, length(v_job.organization_id::text) + 1) <> v_job.organization_id::text || '/'
       OR p_path ~ '\\' OR p_path ~ '(^|/)\.{1,2}(/|$)' THEN
        RAISE EXCEPTION 'FILE_PATH_INVALID: the path must start with the shop id' USING ERRCODE = 'P0001';
    END IF;
    INSERT INTO public.files (id, organization_id, bucket, path, original_name, mime, size_bytes, sha256, purpose,
                              entity_type, entity_id, created_by)
    VALUES (p_file_id, v_job.organization_id, 'tenant-files', p_path, p_original_name, 'application/zip',
            p_size_bytes, p_sha256, 'export', NULL, NULL, v_job.created_by);
    UPDATE public.import_jobs SET status = 'completed', result_file_id = p_file_id, finished_at = now(),
           rows_total = LEAST(p_rows, 2147483647)::integer, rows_ok = LEAST(p_rows, 2147483647)::integer, rows_failed = 0,
           report = report || jsonb_build_object('size_bytes', p_size_bytes, 'uncompressed_bytes', p_uncompressed_bytes,
                                                 'manifest', p_manifest)
    WHERE id = p_job_id RETURNING * INTO v_job;
    INSERT INTO public.audit_log (organization_id, employee_id, action, entity_type, entity_id, severity, after)
    VALUES (v_job.organization_id, v_job.created_by, 'export.completed', 'export_job', p_job_id,
            CASE WHEN v_job.report ->> 'pii' = 'full' THEN 'warning' ELSE 'info' END::public.audit_severity,
            jsonb_build_object('rows', p_rows, 'size_bytes', p_size_bytes, 'pii', v_job.report ->> 'pii',
                               'file_id', p_file_id));
    RETURN jsonb_build_object('status', 'completed', 'changed', true);
END;
$$;

-- The export could not be built (too large, a crash after every attempt, ...).
CREATE FUNCTION public.jobs_export_fail(p_job_id uuid, p_code text, p_detail jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_job public.import_jobs; v_code text := COALESCE(p_code, 'EXPORT_FAILED');
BEGIN
    IF v_code NOT IN ('EXPORT_TOO_LARGE', 'EXPORT_PERMISSION_LOST', 'EXPORT_SHOP_NOT_ACTIVE', 'EXPORT_FAILED') THEN
        v_code := 'EXPORT_FAILED';
    END IF;
    SELECT * INTO v_job FROM public.import_jobs j WHERE j.id = p_job_id AND j.kind = 'full_export' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'EXPORT_NOT_FOUND' USING ERRCODE = 'P0001'; END IF;
    IF v_job.status <> 'importing' THEN
        RETURN jsonb_build_object('status', v_job.status, 'changed', false);
    END IF;
    UPDATE public.import_jobs SET status = 'failed', finished_at = now(),
           report = report || jsonb_build_object('error_code', v_code, 'error_detail', COALESCE(p_detail, '{}'::jsonb))
    WHERE id = p_job_id RETURNING * INTO v_job;
    INSERT INTO public.audit_log (organization_id, employee_id, action, entity_type, entity_id, severity, after)
    VALUES (v_job.organization_id, v_job.created_by, 'export.failed', 'export_job', p_job_id, 'warning',
            jsonb_build_object('error_code', v_code, 'pii', v_job.report ->> 'pii') || COALESCE(p_detail, '{}'::jsonb));
    RETURN jsonb_build_object('status', 'failed', 'changed', true);
END;
$$;

-- Zips older than 7 days that are still in storage (the daily export.cleanup job removes the
-- objects, then reports them done).
CREATE FUNCTION public.jobs_export_cleanup_list(p_org uuid, p_keep_days integer)
RETURNS TABLE (file_id uuid, path text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT f.id, f.path
    FROM public.import_jobs j
    JOIN public.files f ON f.id = j.result_file_id AND f.organization_id = j.organization_id
    WHERE j.organization_id = p_org AND j.kind = 'full_export' AND j.status = 'completed'
      AND f.purpose = 'export' AND f.deleted_at IS NULL
      AND f.created_at < now() - make_interval(days => GREATEST(p_keep_days, 1))
    ORDER BY f.created_at
    LIMIT 100
$$;

CREATE FUNCTION public.jobs_export_cleanup_done(p_org uuid, p_file_ids uuid[])
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_n integer;
BEGIN
    UPDATE public.files f SET deleted_at = now()
    WHERE f.organization_id = p_org AND f.id = ANY (p_file_ids) AND f.purpose = 'export' AND f.deleted_at IS NULL
      AND EXISTS (SELECT 1 FROM public.import_jobs j WHERE j.result_file_id = f.id AND j.kind = 'full_export');
    GET DIAGNOSTICS v_n = ROW_COUNT;
    IF v_n > 0 THEN
        INSERT INTO public.audit_log (organization_id, action, entity_type, severity, after)
        VALUES (p_org, 'export.file_removed', 'export_job', 'info', jsonb_build_object('files', v_n));
    END IF;
    RETURN v_n;
END;
$$;

