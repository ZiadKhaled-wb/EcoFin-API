$$;

-- A queued or running export stops at the next page and ends 'cancelled'. Any other state is
-- returned as it is (cancelling a finished export changes nothing).
CREATE FUNCTION public.cancel_export(p_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_job public.import_jobs;
BEGIN
    PERFORM app.require_permission('export.data');
    SELECT * INTO v_job FROM public.import_jobs j
    WHERE j.id = p_id AND j.organization_id = app.current_org_id() AND j.kind = 'full_export' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'EXPORT_NOT_FOUND' USING ERRCODE = 'P0001'; END IF;
    IF v_job.status = 'importing' THEN
        UPDATE public.import_jobs SET status = 'cancelled', finished_at = now() WHERE id = p_id RETURNING * INTO v_job;
        PERFORM app.write_audit('export.cancelled', 'export_job', p_id, NULL, jsonb_build_object('pii', v_job.report ->> 'pii'));
    END IF;
    RETURN app.export_job_json(v_job);
END;
$$;

-- F14's signed link does not audit reads, so the download of an export zip is recorded here (the API
-- calls it before it hands the link out). A file that is not the zip of a full export changes nothing.
CREATE FUNCTION public.record_export_download(p_file_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_job public.import_jobs;
BEGIN
    PERFORM app.require_permission('export.data');
    SELECT * INTO v_job FROM public.import_jobs j
    WHERE j.organization_id = app.current_org_id() AND j.kind = 'full_export' AND j.result_file_id = p_file_id;
    IF NOT FOUND THEN RETURN; END IF;
    IF v_job.report ->> 'pii' = 'full' AND NOT app.has_permission('customer.view_pii') THEN
        RAISE EXCEPTION 'PERMISSION_DENIED: customer.view_pii' USING ERRCODE = '42501';
    END IF;
    PERFORM app.write_audit('export.downloaded', 'export_job', v_job.id, NULL,
        jsonb_build_object('file_id', p_file_id, 'pii', v_job.report ->> 'pii'), NULL, NULL,
        CASE WHEN v_job.report ->> 'pii' = 'full' THEN 'warning' ELSE 'info' END::public.audit_severity);
END;
$$;

-- 5. The background job (service role) -----------------------------------------------------------

-- Everything the worker needs before it opens the snapshot. Re-checks the requester: an employee
-- who lost export.data (or customer.view_pii for a full export) meanwhile ends the job 'failed'.
CREATE FUNCTION public.jobs_export_prepare(p_job_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    v_job public.import_jobs; v_org public.organizations; v_pii text; v_why text; v_tables text[]; v_t text;
    v_cols jsonb := '{}'::jsonb; v_keys jsonb := '{}'::jsonb; v_compact jsonb := '{}'::jsonb; v_migration text;
BEGIN
    SELECT * INTO v_job FROM public.import_jobs j WHERE j.id = p_job_id AND j.kind = 'full_export' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'EXPORT_NOT_FOUND' USING ERRCODE = 'P0001'; END IF;
    IF v_job.status <> 'importing' THEN
        RETURN jsonb_build_object('status', v_job.status, 'changed', false);
    END IF;
    SELECT * INTO v_org FROM public.organizations o WHERE o.id = v_job.organization_id;
    v_pii := COALESCE(v_job.report ->> 'pii', 'masked');
    IF v_org.status <> 'active' THEN
        v_why := 'EXPORT_SHOP_NOT_ACTIVE';
    ELSIF v_job.created_by IS NULL OR NOT app.employee_has_permission(v_job.created_by, 'export.data')
          OR (v_pii = 'full' AND NOT app.employee_has_permission(v_job.created_by, 'customer.view_pii')) THEN
        v_why := 'EXPORT_PERMISSION_LOST';
    END IF;
    IF v_why IS NOT NULL THEN
        UPDATE public.import_jobs SET status = 'failed', finished_at = now(),
               report = report || jsonb_build_object('error_code', v_why)
        WHERE id = p_job_id RETURNING * INTO v_job;
        INSERT INTO public.audit_log (organization_id, employee_id, action, entity_type, entity_id, severity, after)
        VALUES (v_job.organization_id, v_job.created_by, 'export.failed', 'export_job', p_job_id, 'warning',
                jsonb_build_object('error_code', v_why, 'pii', v_pii));
        RETURN jsonb_build_object('status', 'failed', 'changed', true);
    END IF;

    v_tables := app.export_tables();
    FOREACH v_t IN ARRAY v_tables LOOP
        v_cols := v_cols || jsonb_build_object(v_t, to_jsonb(app.export_columns(v_t)));
        v_keys := v_keys || jsonb_build_object(v_t, to_jsonb(app.export_key_columns(v_t)));
        -- jsonb and array columns: their text is JSON, which the CSV writes compact.
        v_compact := v_compact || jsonb_build_object(v_t, COALESCE((
            SELECT to_jsonb(array_agg(a.attname::text ORDER BY a.attnum))
            FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_type ty ON ty.oid = a.atttypid
            WHERE a.attrelid = ('public.' || quote_ident(v_t))::regclass AND a.attnum > 0 AND NOT a.attisdropped
              AND (ty.typname = 'jsonb' OR ty.typcategory = 'A') AND NOT app.export_column_excluded(v_t, a.attname::text)),
            '[]'::jsonb));
    END LOOP;
    IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN
        EXECUTE 'SELECT version || ''_'' || COALESCE(name, '''') FROM supabase_migrations.schema_migrations ORDER BY version DESC LIMIT 1'
            INTO v_migration;
    END IF;
    UPDATE public.import_jobs SET report = report || jsonb_build_object('started_at', now())
    WHERE id = p_job_id AND NOT report ? 'started_at';
    RETURN jsonb_build_object(
        'status', 'importing', 'changed', true, 'organization_id', v_job.organization_id, 'pii', v_pii,
        'requested_by', (SELECT jsonb_build_object('id', e.id, 'name', e.full_name) FROM public.employees e
                         WHERE e.id = v_job.created_by AND e.organization_id = v_job.organization_id),
        'shop', jsonb_build_object('id', v_org.id, 'name', v_org.name, 'tenant_slug', v_org.tenant_slug),
        'migration', COALESCE(v_migration, 'unknown'),
        'tables', to_jsonb(v_tables), 'columns', v_cols, 'keys', v_keys, 'json_columns', v_compact);
END;
$$;

